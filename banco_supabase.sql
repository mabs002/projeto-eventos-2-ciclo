-- -----------------------------------------------------------------------------
-- 3. GATILHO AUTOMÁTICO DE VAGAS (TRIGGER)
-- Desconta ao cadastrar inscrição e devolve ao cancelar/excluir
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.ajustar_vagas_evento()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF tg_op = 'INSERT' THEN
    UPDATE public.eventos
       SET vagas_restantes = vagas_restantes - 1
     WHERE id = new.id_evento
       AND vagas_restantes > 0;

    IF NOT found THEN
      RAISE EXCEPTION 'Evento sem vagas disponíveis'
        USING errcode = 'P0001', hint = 'vagas_esgotadas';
    END IF;

    RETURN new;
  END IF;

  IF tg_op = 'DELETE' THEN
    UPDATE public.eventos
       SET vagas_restantes = least(vagas_restantes + 1, vagas_totais)
     WHERE id = old.id_evento;

    RETURN old;
  END IF;

  RETURN null;
END;
$$;

REVOKE ALL ON FUNCTION public.ajustar_vagas_evento() FROM public, anon, authenticated;

DROP TRIGGER IF EXISTS trg_inscricao_desconta_vaga ON public.eventos_participantes;
CREATE TRIGGER trg_inscricao_desconta_vaga
  BEFORE INSERT ON public.eventos_participantes
  FOR EACH ROW EXECUTE FUNCTION public.ajustar_vagas_evento();

DROP TRIGGER IF EXISTS trg_inscricao_devolve_vaga ON public.eventos_participantes;
CREATE TRIGGER trg_inscricao_devolve_vaga
  AFTER DELETE ON public.eventos_participantes
  FOR EACH ROW EXECUTE FUNCTION public.ajustar_vagas_evento();

-- -----------------------------------------------------------------------------
-- 4. FUNÇÃO RPC DE INSCRIÇÃO PÚBLICA
-- Validada e transacional com código gerado
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.inscrever_participante(
  p_id_evento       BIGINT,
  p_nome            TEXT,
  p_email           TEXT,
  p_documento       TEXT,
  p_data_nascimento DATE,
  p_whatsapp        TEXT
)
RETURNS TABLE (inscricao_id BIGINT, codigo TEXT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_nome            TEXT := btrim(coalesce(p_nome, ''));
  v_email           TEXT := lower(btrim(coalesce(p_email, '')));
  v_documento       TEXT := regexp_replace(coalesce(p_documento, ''), '\D', '', 'g');
  v_whatsapp        TEXT := regexp_replace(coalesce(p_whatsapp, ''), '\D', '', 'g');
  v_data_evento     DATE;
  v_participante_id BIGINT;
  v_inscricao_id    BIGINT;
BEGIN
  -- 1. Validação de dados de entrada
  IF length(v_nome) < 3 OR length(v_nome) > 120 THEN
    RAISE EXCEPTION 'Nome inválido' USING errcode = '22023', hint = 'nome_invalido';
  END IF;

  IF v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' OR length(v_email) > 254 THEN
    RAISE EXCEPTION 'E-mail inválido' USING errcode = '22023', hint = 'email_invalido';
  END IF;

  IF length(v_documento) <> 11 THEN
    RAISE EXCEPTION 'CPF inválido' USING errcode = '22023', hint = 'documento_invalido';
  END IF;

  IF length(v_whatsapp) NOT BETWEEN 10 AND 13 THEN
    RAISE EXCEPTION 'WhatsApp inválido' USING errcode = '22023', hint = 'whatsapp_invalido';
  END IF;

  IF p_data_nascimento IS NULL
     OR p_data_nascimento >= current_date
     OR p_data_nascimento < current_date - interval '120 years' THEN
    RAISE EXCEPTION 'Data de nascimento inválida' USING errcode = '22023', hint = 'data_nascimento_invalida';
  END IF;

  -- 2. Evento existe e ainda não ocorreu
  SELECT data INTO v_data_evento FROM public.eventos WHERE id = p_id_evento;

  IF NOT found THEN
    RAISE EXCEPTION 'Evento não encontrado' USING errcode = 'P0002', hint = 'evento_nao_encontrado';
  END IF;

  IF v_data_evento < (now() AT TIME ZONE 'America/Sao_Paulo')::date THEN
    RAISE EXCEPTION 'Inscrições encerradas' USING errcode = 'P0001', hint = 'inscricoes_encerradas';
  END IF;

  -- 3. Participante: insere ou reaproveita pelo e-mail
  SELECT id INTO v_participante_id FROM public.participantes WHERE lower(email) = v_email;

  IF v_participante_id IS NULL THEN
    INSERT INTO public.participantes (nome, email, documento, data_nascimento, whatsapp)
    VALUES (v_nome, v_email, v_documento, p_data_nascimento, v_whatsapp)
    RETURNING id INTO v_participante_id;
  END IF;

  -- 4. Inscrição única por oficina
  IF EXISTS (
    SELECT 1 FROM public.eventos_participantes
     WHERE id_evento = p_id_evento AND id_participante = v_participante_id
  ) THEN
    RAISE EXCEPTION 'Participante já inscrito neste evento' USING errcode = 'P0001', hint = 'ja_inscrito';
  END IF;

  -- 5. Criação da inscrição (gatilho desconta vaga automaticamente)
  INSERT INTO public.eventos_participantes (id_evento, id_participante)
  VALUES (p_id_evento, v_participante_id)
  RETURNING id INTO v_inscricao_id;

  RETURN QUERY SELECT v_inscricao_id, 'INSC-' || lpad(v_inscricao_id::text, 6, '0');
END;
$$;

REVOKE ALL ON FUNCTION public.inscrever_participante(BIGINT, TEXT, TEXT, TEXT, DATE, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.inscrever_participante(BIGINT, TEXT, TEXT, TEXT, DATE, TEXT) TO anon, authenticated;

