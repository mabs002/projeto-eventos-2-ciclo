-- Categorias Gastronômicas
CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    nome TEXT NOT NULL,
    slug TEXT NOT NULL,
    cor TEXT DEFAULT '#e04826'
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_categorias_slug ON public.categorias (slug);

-- Oficinas & Experiências Gastronômicas
CREATE TABLE IF NOT EXISTS public.eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    nome TEXT NOT NULL,
    slug TEXT,
    categoria_id BIGINT REFERENCES public.categorias(id) ON DELETE SET NULL,
    data DATE NOT NULL,
    horario TEXT,
    local TEXT,
    endereco TEXT,
    responsavel TEXT,
    vagas_totais INTEGER DEFAULT 20 NOT NULL,
    vagas_restantes INTEGER DEFAULT 20 NOT NULL,
    destaque BOOLEAN DEFAULT FALSE NOT NULL,
    descricao TEXT,
    imagem_url TEXT
);

-- Idempotência: adiciona a coluna caso a tabela já tenha sido criada anteriormente
ALTER TABLE public.eventos ADD COLUMN IF NOT EXISTS imagem_url TEXT;

CREATE INDEX IF NOT EXISTS idx_eventos_slug ON public.eventos (slug);

-- Participantes / Alunos
CREATE TABLE IF NOT EXISTS public.participantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    nome TEXT NOT NULL,
    email TEXT NOT NULL,
    documento TEXT,
    data_nascimento DATE,
    whatsapp TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_participantes_email ON public.participantes (email);

-- Inscrições em Oficinas (Vínculo Evento <-> Participante)
CREATE TABLE IF NOT EXISTS public.eventos_participantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    id_evento BIGINT NOT NULL REFERENCES public.eventos(id) ON DELETE CASCADE,
    id_participante BIGINT NOT NULL REFERENCES public.participantes(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_eventos_participantes_unique ON public.eventos_participantes (id_evento, id_participante);

-- Remove a tabela legada 'usuarios' caso ainda exista no banco
DROP TABLE IF EXISTS public.usuarios CASCADE;

-- Tabela de Inscrições Legada (mantida para compatibilidade transparente)
CREATE TABLE IF NOT EXISTS public.inscricoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_inscricao TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    evento_id BIGINT REFERENCES public.eventos(id) ON DELETE CASCADE,
    codigo_confirmacao VARCHAR(50) NOT NULL
);

